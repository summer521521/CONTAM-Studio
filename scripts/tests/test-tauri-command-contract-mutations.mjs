import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";

const root = process.cwd();
const checker = path.join(root, "scripts", "tests", "test-tauri-command-contract.mjs");
const failures = [];

function copyFile(relativePath, targetRoot) {
  const source = path.join(root, relativePath);
  const target = path.join(targetRoot, relativePath);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(source, target);
}

function copyBaseline(targetRoot) {
  for (const file of [
    "contracts/tauri-commands.v1.json",
    "src-tauri/src/lib.rs",
    "src-tauri/build.rs",
    "src-tauri/capabilities/default.json",
    "tsconfig.json",
    "tsconfig.app.json",
  ]) {
    copyFile(file, targetRoot);
  }
  fs.cpSync(path.join(root, "src", "app"), path.join(targetRoot, "src", "app"), { recursive: true });
  fs.cpSync(
    path.join(root, "src-tauri", "permissions", "autogenerated"),
    path.join(targetRoot, "src-tauri", "permissions", "autogenerated"),
    { recursive: true },
  );
}

function assertFails(name, mutate) {
  const targetRoot = fs.mkdtempSync(path.join(path.dirname(root), "tauri-contract-mutation-"));
  try {
    copyBaseline(targetRoot);
    mutate(targetRoot);
    const result = spawnSync(
      process.execPath,
      [checker, "--root", targetRoot, "--strict-generated-permissions"],
      { cwd: root, encoding: "utf8" },
    );
    if (result.status === 0) {
      failures.push(`${name} unexpectedly passed`);
    }
  } finally {
    fs.rmSync(targetRoot, { recursive: true, force: true });
  }
}

assertFails("missing lib.rs", (targetRoot) => {
  fs.rmSync(path.join(targetRoot, "src-tauri", "src", "lib.rs"));
});
assertFails("missing build.rs", (targetRoot) => {
  fs.rmSync(path.join(targetRoot, "src-tauri", "build.rs"));
});
assertFails("missing capability", (targetRoot) => {
  fs.rmSync(path.join(targetRoot, "src-tauri", "capabilities", "default.json"));
});
assertFails("missing generated permission", (targetRoot) => {
  fs.rmSync(path.join(targetRoot, "src-tauri", "permissions", "autogenerated", "select_and_read_prj_zones.toml"));
});
assertFails("missing TypeScript command", (targetRoot) => {
  const file = path.join(targetRoot, "src", "app", "desktop-api.ts");
  const source = fs.readFileSync(file, "utf8");
  fs.writeFileSync(file, source.replace('return invoke<DesktopOpenResponse>("select_and_read_prj_zones", { requestId });', 'return Promise.reject(new Error("removed"));'), "utf8");
});
assertFails("modified TypeScript payload key", (targetRoot) => {
  const file = path.join(targetRoot, "src", "app", "desktop-api.ts");
  const source = fs.readFileSync(file, "utf8");
  fs.writeFileSync(file, source.replace('{ requestId });', '{ requestID: requestId });'), "utf8");
});

if (failures.length > 0) {
  for (const failure of failures) {
    console.error(`[FAIL] ${failure}`);
  }
  process.exitCode = 1;
} else {
  console.log("Tauri command contract mutation tests passed: six independent deletions/mutations failed closed.");
}
